"""Generate the appendix order and coverage guide from frozen PDF snapshots.

Run from any directory after editing assets/appendix/sources.json.
Only the Python standard library is needed. The generated TeX is versioned,
so the normal slides build needs neither this script nor the MOVER checkout.
"""

import hashlib
import json
from pathlib import Path


def latex_escape(value):
    replacements = {
        "\\": r"\textbackslash{}", "&": r"\&", "%": r"\%", "$": r"\$",
        "#": r"\#", "_": r"\_", "{": r"\{", "}": r"\}",
        "~": r"\textasciitilde{}", "^": r"\textasciicircum{}",
    }
    return "".join(replacements.get(char, char) for char in value)


def main():
    directory = Path(__file__).resolve().parent
    assets = directory.parents[1] / "assets/appendix"
    manifest = json.loads((assets / "sources.json").read_text())
    selected = {source: [] for source in manifest["sources"]}
    for group in manifest["groups"]:
        if group.get("kind") != "native":
            selected[group["source"]].extend(group["pages"])

    for key, source in manifest["sources"].items():
        digest = hashlib.sha256((assets / source["file"]).read_bytes()).hexdigest()
        if digest != source["sha256"]:
            raise ValueError(f"Snapshot checksum changed: {source['file']}")
        if len(selected[key]) != len(set(selected[key])):
            raise ValueError(f"Repeated source pages: {key}")
        excluded = (set(map(int, manifest["excluded_weekly_pages"]))
                    if key == "weekly" else set())
        expected = set(range(1, source["pages"] + 1))
        if set(selected[key]) & excluded or set(selected[key]) | excluded != expected:
            raise ValueError(f"Incomplete source coverage: {key}")

    slides = ["% Generated by final/appendix/generate.py; edit sources.json.\n"]
    contents = [r"\renewcommand{\arraystretch}{1.65}",
                r"\begin{tabular}{@{}p{0.65cm}p{10.5cm}r@{}}"]
    coverage = ["# Appendix Source Coverage", "",
                f"Presentation date: **{manifest['presentation_date']}**. "
                f"The original {manifest['main_pages']} talk pages precede the appendix.",
                "", manifest["coverage_policy"], "", manifest["import_policy"], "",
                "| Appendix Pages | PDF Pages | Section | Source Pages |",
                "| --- | --- | --- | --- |"]
    entries = []
    # The appendix begins with its cover (A1) and contents (A2).
    position = 3
    for group in manifest["groups"]:
        native = group.get("kind") == "native"
        source = None if native else manifest["sources"][group["source"]]
        start = position
        end = start + len(group["pages"])
        title = latex_escape(group["title"])
        contents.append(
            rf"\textbf{{{group['letter']}}} & "
            rf"\hyperlink{{appendix-{group['id']}}}{{{title}}} & "
            rf"\hyperlink{{appendix-{group['id']}}}{{A{start}--A{end}}} \\")
        slides.append(
            rf"\FinalAppendixDivider{{{group['letter']}}}{{{title}}}"
            rf"{{{group['id']}}}{{{latex_escape(group['description'])}}}")
        source_pages = ("Native LaTeX: " + ", ".join(page["title"] for page in group["pages"])
                        if native else group["source"] + ": " + ", ".join(map(str, group["pages"])))
        coverage.append(
            f"| A{start}–A{end} | {manifest['main_pages'] + start}–"
            f"{manifest['main_pages'] + end} | {group['letter']}. {group['title']} "
            f"| {source_pages} |")
        position += 1
        for page in group["pages"]:
            if native:
                page_title = page["title"]
                slides.append(rf"\input{{{page['input']}}}")
                source_label = "Native LaTeX"
            else:
                page_title = source["page_titles"][str(page)]
                command = ("FinalWeeklyAppendixPage" if group["source"] == "weekly"
                           else "FinalExperimentAppendixPage")
                slides.append(rf"\{command}{{{page}}}{{{latex_escape(page_title)}}}")
                source_label = f"{group['source']} {page}"
            entries.append(f"| A{position} | {manifest['main_pages'] + position} "
                           f"| {source_label} | {page_title} |")
            position += 1
        slides.append("")

    contents.append(r"\end{tabular}")
    coverage.extend(["", f"Total: **{position - 1} appendix pages**, "
                     f"**{manifest['main_pages'] + position - 1} PDF pages**.", "",
                     "## Page-by-Page Mapping", "",
                     "| Appendix Page | PDF Page | Source Page | Original Title |",
                     "| --- | --- | --- | --- |", *entries,
                     "", "## Excluded Weekly Pages", "",
                     "| Source Page | Reason |", "| --- | --- |"])
    for page, reason in manifest["excluded_weekly_pages"].items():
        coverage.append(f"| {page} | {reason} |")
    coverage.extend(["", "All 20 experiments-report pages are included, including its "
                     "custom-experiments divider. Content summarized in the main "
                     "talk is retained in full here so the appendix is complete.", ""])
    (directory / "slides.generated.tex").write_text("\n".join(slides))
    (directory / "contents.generated.tex").write_text("\n".join(contents) + "\n")
    (assets / "coverage.md").write_text("\n".join(coverage))
    print(f"Generated {position - 1} appendix pages; "
          f"{sum(map(len, selected.values()))} imported content pages.")


if __name__ == "__main__":
    main()
